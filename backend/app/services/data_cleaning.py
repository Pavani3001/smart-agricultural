"""
Data cleaning and validation service for sensor readings.

Provides functions to validate individual readings, detect duplicates,
handle missing data gaps, and normalize units. Uses pandas for efficient
batch processing.

Quality flags:
    VALID        — passed all validation checks
    SIMULATED    — generated by the sensor simulator
    INTERPOLATED — gap-filled by interpolation
    STALE        — data is older than expected or from a fallback source
    INVALID      — failed validation (out-of-range values)
"""

import logging
from datetime import datetime, timedelta, timezone
from typing import List, Tuple, Optional

import pandas as pd

logger = logging.getLogger(__name__)

# ── Constants ──────────────────────────────────────────────────────────────

# Physical limits for sensor readings
SOIL_MOISTURE_MIN = 0.0
SOIL_MOISTURE_MAX = 100.0
TEMPERATURE_MIN = -50.0
TEMPERATURE_MAX = 60.0

# Duplicate detection window
DUPLICATE_WINDOW_SECONDS = 1

# Maximum acceptable gap between consecutive readings
MAX_GAP_MINUTES = 15

# Quality flag constants
FLAG_VALID = "VALID"
FLAG_SIMULATED = "SIMULATED"
FLAG_INTERPOLATED = "INTERPOLATED"
FLAG_STALE = "STALE"
FLAG_INVALID = "INVALID"


def validate_sensor_reading(
    soil_moisture: Optional[float],
    temperature: Optional[float],
) -> Tuple[bool, str, str]:
    """
    Validate a single sensor reading against physical limits.

    Args:
        soil_moisture: Soil moisture percentage (0-100), or None.
        temperature: Temperature in Celsius (-50 to 60), or None.

    Returns:
        Tuple of (is_valid, quality_flag, reason):
            - is_valid: True if the reading passes validation.
            - quality_flag: Suggested quality flag for the reading.
            - reason: Human-readable validation result message.
    """
    issues: List[str] = []

    if soil_moisture is None and temperature is None:
        return False, FLAG_INVALID, "Both soil_moisture and temperature readings are missing"

    # Check soil moisture bounds when provided
    if soil_moisture is not None:
        if soil_moisture < SOIL_MOISTURE_MIN or soil_moisture > SOIL_MOISTURE_MAX:
            issues.append(
                f"soil_moisture {soil_moisture}% out of range "
                f"[{SOIL_MOISTURE_MIN}-{SOIL_MOISTURE_MAX}]"
            )

    # Check temperature bounds when provided
    if temperature is not None:
        if temperature < TEMPERATURE_MIN or temperature > TEMPERATURE_MAX:
            issues.append(
                f"temperature {temperature}°C out of range "
                f"[{TEMPERATURE_MIN}-{TEMPERATURE_MAX}]"
            )

    if issues:
        return False, FLAG_INVALID, "; ".join(issues)

    return True, FLAG_VALID, "Reading is valid"


def detect_duplicates(
    sensor_id: str,
    timestamp: datetime,
    existing_timestamps: List[datetime],
) -> bool:
    """
    Detect whether a reading is a duplicate based on sensor_id + timestamp.

    A reading is considered a duplicate if another reading from the same
    sensor exists within DUPLICATE_WINDOW_SECONDS of the given timestamp.

    Args:
        sensor_id: The external sensor identifier.
        timestamp: The timestamp of the reading to check.
        existing_timestamps: List of timestamps already stored for this sensor.

    Returns:
        True if the reading is a duplicate, False otherwise.
    """
    window = timedelta(seconds=DUPLICATE_WINDOW_SECONDS)
    for existing_ts in existing_timestamps:
        t1 = timestamp
        t2 = existing_ts
        if t1.tzinfo is not None and t2.tzinfo is None:
            t2 = t2.replace(tzinfo=timezone.utc)
        elif t1.tzinfo is None and t2.tzinfo is not None:
            t1 = t1.replace(tzinfo=timezone.utc)
        if abs(t1 - t2) <= window:
            logger.debug(
                "Duplicate detected for sensor %s at %s (existing: %s)",
                sensor_id,
                timestamp,
                existing_ts,
            )
            return True
    return False


def handle_missing_readings(
    readings_df: pd.DataFrame,
    max_gap_minutes: int = MAX_GAP_MINUTES,
) -> pd.DataFrame:
    """
    Flag gaps in time-series data where consecutive readings are more than
    `max_gap_minutes` apart.

    Adds a 'gap_flag' column:
        - 'MISSING' for the reading immediately after a gap
        - None for normal readings

    Args:
        readings_df: DataFrame with at least 'sensor_id' and 'timestamp' columns,
                     sorted by sensor_id and timestamp ascending.
        max_gap_minutes: Maximum allowed minutes between consecutive readings.

    Returns:
        The input DataFrame with an added 'gap_flag' column.
    """
    if readings_df.empty:
        readings_df["gap_flag"] = None
        return readings_df

    # Work on a copy to avoid side effects
    df = readings_df.copy()
    df = df.sort_values(["sensor_id", "timestamp"]).reset_index(drop=True)

    # Calculate time difference within each sensor group
    df["prev_timestamp"] = df.groupby("sensor_id")["timestamp"].shift(1)
    df["time_diff"] = (df["timestamp"] - df["prev_timestamp"]).dt.total_seconds() / 60.0

    # Flag readings that follow a gap longer than the threshold
    df["gap_flag"] = None
    gap_mask = df["time_diff"] > max_gap_minutes
    df.loc[gap_mask, "gap_flag"] = "MISSING"

    if gap_mask.any():
        gap_count = gap_mask.sum()
        logger.info("Detected %d gap(s) exceeding %d minutes", gap_count, max_gap_minutes)

    # Clean up helper columns
    df.drop(columns=["prev_timestamp", "time_diff"], inplace=True)
    return df


def normalize_reading(
    soil_moisture: Optional[float],
    temperature: Optional[float],
) -> Tuple[Optional[float], Optional[float]]:
    """
    Normalize sensor reading values to ensure correct units.

    Currently enforces:
        - Soil moisture clamped to [0, 100] (percentage).
        - Temperature kept in Celsius (no conversion needed).

    Future: add unit conversion logic here if sensors report in
    different units.

    Args:
        soil_moisture: Raw soil moisture value.
        temperature: Raw temperature value.

    Returns:
        Tuple of (normalized_moisture, normalized_temperature).
    """
    norm_moisture = soil_moisture
    norm_temp = temperature

    # Clamp moisture to valid percentage range
    if norm_moisture is not None:
        norm_moisture = max(SOIL_MOISTURE_MIN, min(SOIL_MOISTURE_MAX, norm_moisture))

    # Clamp temperature to valid physical range
    if norm_temp is not None:
        norm_temp = max(TEMPERATURE_MIN, min(TEMPERATURE_MAX, norm_temp))

    return norm_moisture, norm_temp


def clean_batch(readings_df: pd.DataFrame) -> pd.DataFrame:
    """
    Run the full cleaning pipeline on a batch of readings.

    Steps:
        1. Validate each row against physical limits.
        2. Normalize out-of-range values.
        3. Flag gaps in the time series.

    Args:
        readings_df: DataFrame with columns: sensor_id, field_id,
                     soil_moisture_percent, temperature_celsius,
                     timestamp, is_simulated, quality_flag.

    Returns:
        Cleaned DataFrame with updated quality_flag and gap_flag columns.
    """
    if readings_df.empty:
        return readings_df

    df = readings_df.copy()

    # Step 1 & 2: Validate and normalize each row
    validation_results = df.apply(
        lambda row: validate_sensor_reading(
            row.get("soil_moisture_percent"),
            row.get("temperature_celsius"),
        ),
        axis=1,
        result_type="expand",
    )
    df["_is_valid"] = validation_results[0]
    df["_suggested_flag"] = validation_results[1]

    # Mark invalid readings but do NOT drop them — preserve with INVALID flag
    invalid_mask = ~df["_is_valid"]
    # Only overwrite quality_flag if it was VALID (preserve SIMULATED etc.)
    overwrite_mask = invalid_mask & (df["quality_flag"] == FLAG_VALID)
    df.loc[overwrite_mask, "quality_flag"] = FLAG_INVALID

    # Normalize values (clamp to valid ranges)
    normalized = df.apply(
        lambda row: normalize_reading(
            row.get("soil_moisture_percent"),
            row.get("temperature_celsius"),
        ),
        axis=1,
        result_type="expand",
    )
    df["soil_moisture_percent"] = normalized[0]
    df["temperature_celsius"] = normalized[1]

    # Step 3: Flag time-series gaps
    df = handle_missing_readings(df)

    # Clean up internal columns
    df.drop(columns=["_is_valid", "_suggested_flag"], inplace=True, errors="ignore")

    logger.info(
        "Batch cleaning complete: %d readings, %d invalid",
        len(df),
        invalid_mask.sum(),
    )
    return df
