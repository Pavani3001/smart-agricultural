"""
SQLAlchemy model for the SensorReading entity.

Maps to the 'sensor_readings' hypertable defined in init_db.sql.
Stores time-series soil moisture and temperature data collected from sensors.
"""

from sqlalchemy import Column, BigInteger, Integer, String, Float, Boolean, DateTime, CheckConstraint
from sqlalchemy.sql import func
from datetime import datetime, timezone

from ..database import Base


class SensorReading(Base):
    """
    ORM model for a single sensor reading (time-series row).

    This table is a TimescaleDB hypertable partitioned by `timestamp`.
    Quality flags indicate data provenance and reliability.

    Attributes:
        id: Auto-incrementing big integer PK.
        sensor_id: External sensor identifier (string, not FK — matches sensors.sensor_id).
        field_id: Field where the reading was taken.
        soil_moisture_percent: Soil moisture as a percentage (0-100).
        temperature_celsius: Ambient / soil temperature in °C.
        is_simulated: True if the reading was generated by the simulator.
        quality_flag: Data quality indicator (VALID, SIMULATED, INTERPOLATED, STALE, INVALID).
        timestamp: UTC timestamp of the reading.
        ingested_at: UTC timestamp when the row was stored.
    """

    __tablename__ = "sensor_readings"

    id = Column(BigInteger().with_variant(Integer, "sqlite"), primary_key=True, autoincrement=True)
    sensor_id = Column(String(50), nullable=False, index=True)
    field_id = Column(Integer, nullable=False, index=True)
    soil_moisture_percent = Column(Float, nullable=True)
    temperature_celsius = Column(Float, nullable=True)
    is_simulated = Column(Boolean, default=False)
    quality_flag = Column(String(20), default="VALID")
    timestamp = Column(DateTime(timezone=True), nullable=False)
    ingested_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        default=lambda: datetime.now(timezone.utc),
    )

    __table_args__ = (
        CheckConstraint(
            "quality_flag IN ('VALID', 'SIMULATED', 'INTERPOLATED', 'STALE', 'INVALID')",
            name="ck_sensor_readings_quality_flag",
        ),
    )

    def __repr__(self) -> str:
        return (
            f"<SensorReading(id={self.id}, sensor_id='{self.sensor_id}', "
            f"moisture={self.soil_moisture_percent}%, ts={self.timestamp})>"
        )
